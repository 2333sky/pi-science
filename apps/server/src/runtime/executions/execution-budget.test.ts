import { mkdir, mkdtemp, rm } from "node:fs/promises";
import { join, resolve } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { BACKGROUND_CONTEXT, NodeExecutionEnv } from "@earendil-works/pi-agent-core/node";
import { workspaceFile } from "../../storage/persistence.js";
import { executionBudgetTools } from "../agent/worker/execution-budget.js";
import { budgetHash, readBudget, reserveEvaluation } from "./execution-budget.js";
let root: string | undefined;
afterEach(async () => { vi.unstubAllEnvs(); if (root) await rm(root, { recursive: true, force: true }); });
it("atomically shares generic, research-wide and revision query caps across retries and continuation", async () => {
  await mkdir(resolve("../../.runtime"), { recursive: true }); root = await mkdtemp(join(resolve("../../.runtime"), "evaluation-budget-"));
  const cwd = join(root, "workspace"); await mkdir(cwd); await mkdir(join(cwd, ".pi-science")); vi.stubEnv("PI_SCIENCE_HOME", join(root, "private"));
  const env = { env: new NodeExecutionEnv({ cwd }) };
  const configure = (op: string, values: object) => executionBudgetTools(cwd).tool.execute("budget", values, () => {}, env, { operationId: op, invocationId: "budget", turnId: "turn", getMemo: async () => undefined, setMemo: async () => {} }, BACKGROUND_CONTEXT);
  await configure("first", { research_id: "study", max_seconds: 30, max_executions: 8, max_evaluations: 2 });
  const results = await Promise.allSettled(Array.from({ length: 8 }, (_, i) => reserveEvaluation(cwd, "first", "study", `query-${i}`, "rev", "fingerprint", 1)));
  expect(results.filter((item) => item.status === "fulfilled")).toHaveLength(1);
  const path = workspaceFile(cwd, `execution-budgets/${budgetHash("research:study")}.json`); const budget = (await readBudget(path))!;
  const key = Object.keys(budget.evaluations!)[0]!;
  expect(await reserveEvaluation(cwd, "first", "study", key, "rev", "fingerprint", 1)).toEqual(budget);
  await expect(reserveEvaluation(cwd, "first", "study", key, "rev", "changed", 1)).rejects.toThrow("input changed");
  await configure("continuation", { research_id: "study", max_executions: 100, max_evaluations: 100 });
  expect((await readBudget(path))!.maxEvaluations).toBe(2);
  await reserveEvaluation(cwd, "continuation", "study", "second", "other-rev", "different", 5);
  await expect(reserveEvaluation(cwd, "continuation", "study", "third", "third-rev", "different", 5)).rejects.toThrow("budget exhausted");
  expect((await readBudget(path))!.used).toBe(2);
  await expect(reserveEvaluation(cwd, "unbound", "study", "forged", "rev", "fingerprint", 5)).rejects.toThrow();
  await expect(reserveEvaluation(cwd, "first", "unrelated", "forged", "rev", "fingerprint", 5)).rejects.toThrow("binding mismatch");
});
