import { mkdtemp, mkdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { resolveBrowserExecutable } from './browser-executable.mjs';
const require = createRequire(new URL('../package.json', import.meta.url));
const { chromium } = require('playwright-core');
const { default: AxeBuilder } = await import('@axe-core/playwright');
const repository = fileURLToPath(new URL('../../', import.meta.url));
await mkdir(join(repository, '.cache'), { recursive: true });
const root = await mkdtemp(join(repository, '.cache/native-model-uat-'));
process.env.PI_SCIENCE_HOME = join(root, 'state');
process.env.PI_SCIENCE_WORKSPACES = join(root, 'workspaces');
process.env.PI_SCIENCE_FRONTEND_DIST = join(repository, 'frontend/dist');
process.env.PI_SCIENCE_INTERNAL_TOKEN = 'local-model-uat-token';
delete process.env.PI_SCIENCE_MODEL_CONFIG_BACKEND;
process.env.PI_SCIENCE_AI_TITLES = '0';
process.env.LAB_UAT_MODEL_KEY = 'local-uat-key-never-render';
await mkdir(process.env.PI_SCIENCE_WORKSPACES, { recursive: true });
await mkdir(process.env.PI_SCIENCE_HOME, { recursive: true });
await writeFile(join(process.env.PI_SCIENCE_HOME, 'config.json'), JSON.stringify({ api_keys: { openai: 'old-key-never-adopt' }, custom_providers: [{ id: 'retired-lab', name: 'Retired Lab', models: ['obsolete'], base_url: 'http://127.0.0.1:9999/v1', api: 'openai-completions', api_key: 'old-key-never-adopt' }] }));
const { buildApp } = await import('../../apps/server/dist/app/app.js');
const { loadConfig } = await import('../../apps/server/dist/config/config.js');
const app = buildApp({ ...loadConfig(), port: 0 });
let browser;
try {
  const origin = await app.listen({ host: '127.0.0.1', port: 0 });
  const api = async (path, method = 'GET', body) => {
    const response = await fetch(origin + path, { method, headers: { 'x-pi-science-internal-token': process.env.PI_SCIENCE_INTERNAL_TOKEN, 'Content-Type': 'application/json' }, ...(body ? { body: JSON.stringify(body) } : {}) });
    if (!response.ok) throw new Error(`${path}: ${response.status}`);
    return response.json();
  };
  browser = await chromium.launch({ executablePath: await resolveBrowserExecutable(), headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ locale: 'en-US', viewport: { width: 1280, height: 900 }, extraHTTPHeaders: { 'x-pi-science-internal-token': process.env.PI_SCIENCE_INTERNAL_TOKEN } });
  const page = await context.newPage();
  page.setDefaultTimeout(15000);
  await page.addInitScript(() => { localStorage.setItem('pi-science.locale', JSON.stringify('en')); });
  await page.goto(origin + '/settings');
  await page.getByRole('tab', { name: 'AI Models', exact: true }).click();
  await page.getByRole('button', { name: 'Advanced model configuration', exact: true }).waitFor();
  const initial = await api('/api/model-config');
  if (initial.backend !== 'pi_ai_v1' || Object.keys(initial.config.providers).length) throw new Error('Old settings became active');
  const initialSettings = await api('/api/settings/config');
  if (initialSettings.available_models.length || JSON.stringify(initialSettings).includes('old-key-never-adopt') || (await page.locator('body').innerText()).includes('Retired Lab')) throw new Error('Old configuration leaked into native Settings');
  console.log('PASS default native editor ignores old keys and providers');
  await page.getByRole('button', { name: 'Connect a service', exact: true }).click();
  const dialog = page.getByRole('dialog', { name: 'Connect model service', exact: true });
  const dimensions = async () => { const box = await dialog.boundingBox(); return [box.width, box.height]; };
  const size = await dimensions();
  if (Math.abs(size[0] - 600) > 1 || Math.abs(size[1] - 620) > 1) throw new Error(`Unexpected desktop size: ${size}`);
  await dialog.getByRole('tab', { name: 'Subscription', exact: true }).click();
  await dialog.getByText('Subscription authorization is not available yet').waitFor();
  if (await dialog.getByLabel('API key', { exact: true }).count() || JSON.stringify(await dimensions()) !== JSON.stringify(size)) throw new Error('Subscription isolation or fixed frame failed');
  await dialog.getByRole('tab', { name: 'API', exact: true }).click();
  const providerSearch = dialog.getByRole('textbox', { name: 'Search providers' });
  await providerSearch.fill('no-matching-provider');
  await dialog.getByRole('button', { name: '+ Custom API', exact: true }).click();
  if (JSON.stringify(await dimensions()) !== JSON.stringify(size)) throw new Error('Custom form resized modal');
  console.log('PASS desktop frame stays 600x620 across tabs, search and forms; OAuth remains unavailable');
  await dialog.getByLabel('Provider name', { exact: true }).fill('UAT Lab');
  await dialog.getByLabel('Provider ID', { exact: true }).fill('uat-lab');
  await dialog.getByLabel(/Base URL/).fill('http://127.0.0.1:9999/v1');
  await dialog.getByRole('combobox', { name: /Credential source/ }).selectOption('keyless');
  await dialog.getByLabel(/Manual model IDs/).fill('uat-model');
  await dialog.getByRole('button', { name: 'Save', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  const config = await api('/api/model-config');
  if (!config.config.providers['uat-lab'] || config.revision !== 1) throw new Error('Provider was not atomically committed');
  const search = page.getByRole('textbox', { name: /Search/ });
  await search.fill('UAT Lab');
  await page.getByRole('button', { name: 'UAT Lab', exact: true }).click();
  await page.getByText('Selectable · Inference not verified', { exact: true }).waitFor();
  console.log('PASS native Settings creates a keyless provider and displays separate inference status');
  await api('/api/model-config/providers/uat-lab/credential', 'PUT', { revision: 1, credential: { source: 'environment', environment_variable: 'LAB_UAT_MODEL_KEY' } });
  await page.reload();
  await page.getByRole('tab', { name: 'AI Models', exact: true }).click();
  await page.getByRole('button', { name: 'Advanced model configuration', exact: true }).waitFor();
  await page.getByRole('textbox', { name: /Search/ }).fill('UAT Lab');
  await page.getByText(/Environment: LAB_UAT_MODEL_KEY/).waitFor();
  if ((await page.locator('body').innerText()).includes(process.env.LAB_UAT_MODEL_KEY)) throw new Error('Secret leaked into browser');
  console.log('PASS explicit EnvRef shows its name, hides its value, and requires backend restart for rotation');
  const before = await api('/api/model-selection/default');
  if (before.selection.model !== null) throw new Error('Provider edit changed the default model');
  console.log('PASS provider writes preserve default selection ownership');
  await page.getByRole('button', { name: 'UAT Lab actions', exact: true }).click();
  await page.getByRole('menuitem', { name: 'Manage credentials', exact: true }).click();
  const credentials = page.getByRole('dialog', { name: 'UAT Lab · Manage credentials', exact: true });
  await credentials.getByRole('combobox', { name: /Credential source/ }).selectOption('managed');
  await credentials.getByLabel('API key', { exact: true }).fill('draft-only-key');
  await page.keyboard.press('Escape');
  await credentials.getByText('Discard unsaved changes?').waitFor();
  await credentials.getByRole('button', { name: 'Discard', exact: true }).click();
  await credentials.waitFor({ state: 'hidden' });
  await page.getByRole('button', { name: 'UAT Lab actions', exact: true }).waitFor();
  if (!await page.getByRole('button', { name: 'UAT Lab actions', exact: true }).evaluate((node) => node === document.activeElement)) throw new Error('Focus did not return to the provider menu trigger');
  console.log('PASS credentials are menu-only; Escape respects drafts and restores focus');
  for (const [width, height, mode] of [[1280, 900, 'light'], [1280, 900, 'dark'], [375, 667, 'light']]) {
    await page.setViewportSize({ width, height });
    await page.emulateMedia({ colorScheme: mode });
    await page.evaluate((theme) => { document.documentElement.setAttribute('data-theme', theme); document.documentElement.classList.toggle('dark', theme === 'dark'); }, mode);
    await page.getByRole('button', { name: '+ Connect', exact: true }).click();
    const expected = [Math.min(600, width - 32), Math.min(620, height - 32)];
    const initialBox = await dimensions();
    if (initialBox.some((n, i) => Math.abs(n - expected[i]) > 1)) throw new Error(`Responsive bounds failed: ${initialBox}`);
    await dialog.getByRole('tab', { name: 'Subscription', exact: true }).focus();
    await page.keyboard.press('ArrowLeft');
    await dialog.getByRole('button', { name: '+ Custom API', exact: true }).click();
    if ((await dimensions()).some((n, i) => Math.abs(n - initialBox[i]) > 1)) throw new Error('Responsive detail bounds changed');
    const overflow = await dialog.evaluate((node) => node.scrollWidth > node.clientWidth + 1 || node.scrollHeight > node.clientHeight + 1);
    if (overflow) throw new Error('Modal frame overflows');
    const accessibility = await new AxeBuilder({ page }).include('[role="dialog"][aria-labelledby]').withTags(['wcag2a', 'wcag2aa', 'wcag21aa']).analyze();
    if (accessibility.violations.length) throw new Error(`Modal accessibility: ${JSON.stringify(accessibility.violations.map(({ id, nodes }) => ({ id, targets: nodes.map((node) => node.target) })))}`);
    await dialog.getByLabel('Provider name', { exact: true }).focus();
    await page.keyboard.press('Shift+Tab');
    const footerBounds = await dialog.locator('footer').boundingBox();
    const modalBounds = await dialog.boundingBox();
    if (footerBounds.y + footerBounds.height > modalBounds.y + modalBounds.height + 1) throw new Error('Footer escaped modal');
    const screenshotDirectory = process.env.MODEL_UAT_SCREENSHOTS;
    if (screenshotDirectory) { await mkdir(screenshotDirectory, { recursive: true }); await page.screenshot({ path: join(screenshotDirectory, `models-${width}-${mode}.png`) }); }
    await page.keyboard.press('Escape');
    await dialog.waitFor({ state: 'hidden' });
  }
  console.log('PASS light/dark/mobile frames, keyboard tabs, scroll containment and footer bounds');
} finally {
  await browser?.close();
  await app.close();
  await rm(root, { recursive: true, force: true });
}
